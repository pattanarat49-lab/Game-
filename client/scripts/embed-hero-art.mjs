// Embeds hand-made hero art (PNG files exported from PixelLab) into src/heroArt.data.ts as data
// URIs, so the online build and the single-file solo build both carry it.
//
//   art/heroes/<heroId>/south.png, east.png, north.png, west.png   (one picture per facing)
//   plus, optionally, south-east.png, north-east.png, north-west.png, south-west.png for 8 facings
//   art/props/<name>.png   (other pictures, such as Loki's Asgard; texture key <name>)
//   plus, optionally, attack/<facing>-0.png, -1.png ... : the frames of a basic-attack swing
//
// Run `node scripts/embed-hero-art.mjs` after adding or changing files there.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "fs";

const DIRS = ["south", "east", "north", "west"];
const DIAGONALS = ["south-east", "north-east", "north-west", "south-west"];
const root = "art/heroes";
const out = {};
const attacks = {};
for (const hero of readdirSync(root).sort()) {
  const frames = {};
  for (const dir of DIRS) {
    const file = `${root}/${hero}/${dir}.png`;
    if (!existsSync(file)) throw new Error(`${file} is missing (need ${DIRS.join(", ")})`);
    frames[dir] = `data:image/png;base64,${readFileSync(file).toString("base64")}`;
  }
  // Diagonals come all together or not at all.
  const diag = DIAGONALS.filter((dir) => existsSync(`${root}/${hero}/${dir}.png`));
  if (diag.length && diag.length < 4) throw new Error(`${hero}: has only some diagonal facings (${diag.join(", ")})`);
  for (const dir of diag) frames[dir] = `data:image/png;base64,${readFileSync(`${root}/${hero}/${dir}.png`).toString("base64")}`;
  out[hero] = frames;
  // Basic-attack swing frames, per facing that has them (numbered from 0).
  const atkDir = `${root}/${hero}/attack`;
  if (existsSync(atkDir)) {
    const swing = {};
    for (const file of readdirSync(atkDir)) {
      const m = /^([a-z-]+)-(\d+)\.png$/.exec(file);
      if (!m) continue;
      (swing[m[1]] ??= [])[Number(m[2])] = `data:image/png;base64,${readFileSync(`${atkDir}/${file}`).toString("base64")}`;
    }
    for (const [dir, list] of Object.entries(swing)) {
      if (list.some((f) => !f) || list.length !== Object.keys(list).length) throw new Error(`${hero}: attack/${dir} frames are not numbered 0..n`);
    }
    attacks[hero] = swing;
  }
}
const props = {};
for (const file of existsSync("art/props") ? readdirSync("art/props").sort() : []) {
  if (file.endsWith(".png")) props[file.slice(0, -4)] = `data:image/png;base64,${readFileSync(`art/props/${file}`).toString("base64")}`;
}
writeFileSync(
  "src/heroArt.data.ts",
  "// Generated by scripts/embed-hero-art.mjs from art/heroes/. Do not edit by hand.\n" +
    `export const HERO_ART_DATA: Record<string, Partial<Record<string, string>>> = ${JSON.stringify(out, null, 2)};\n` +
    `export const PROP_ART_DATA: Record<string, string> = ${JSON.stringify(props, null, 2)};\n` +
    `export const HERO_ATTACK_DATA: Record<string, Partial<Record<string, string[]>>> = ${JSON.stringify(attacks, null, 2)};\n`,
);
console.log("Embedded hero art for:", Object.keys(out).join(", "));
