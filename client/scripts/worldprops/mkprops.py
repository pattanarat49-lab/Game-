"""Builds client/src/worldProps.data.ts: the Open World props cut from the user's tileset sheet and
redrawn as crisp pixel art (see pixelize.py). Each sprite: palette + one character per pixel."""
import sys, json
import numpy as np
sys.path.insert(0, sys.argv[3])
from pixelize import cut, outline
from clean import clean
from PIL import Image
src, out = sys.argv[1], sys.argv[2]
OLD = (250, 245, 240)  # the first sheet's paper colour
B = "art/worldprops-buildings.png"  # the user's house / windmill / castle / stall sheet (2026-10-11)
T = "art/worldprops-trees.png"  # the user's oak / cherry / pine / willow sheet (2026-10-11)
SPRITES = {
    # name: (sheet or None for the first sheet, rough box, sheet pixels per sprite pixel, colours, roof hue or None).
    # Every prop is drawn 3 screen px per pixel, the same as the ground, so the whole scene shares one pixel size.
    "tree0": (T, [878, 100, 990, 225], 4.4, 9, None), "tree1": (T, [1300, 95, 1410, 225], 4.4, 9, None), "tree2": (T, [878, 840, 995, 968], 4.4, 9, None),
    "blossom0": (T, [878, 345, 990, 478], 4.4, 9, None),
    "pine0": (T, [882, 585, 982, 725], 5.2, 7, None), "pine1": (T, [1022, 590, 1120, 725], 5.2, 7, None),
    "bush0": (None, [32, 509, 75, 548], 3, 6, None), "bush1": (None, [86, 508, 128, 548], 3, 6, None), "bush2": (None, [268, 509, 312, 550], 3, 8, None), "bush3": (None, [319, 506, 362, 550], 3, 8, None),
    "rock0": (None, [34, 606, 74, 643], 3, 5, None), "rock1": (None, [91, 609, 130, 644], 3, 5, None),
    "house0": (B, [120, 28, 320, 214], 3.3, 22, None), "house1": (B, [120, 28, 320, 214], 3.3, 22, 218),
    "house2": (B, [120, 28, 320, 214], 3.3, 22, 112), "house3": (B, [120, 28, 320, 214], 3.3, 22, 38),
    "stall0": (B, [112, 822, 325, 965], 4.6, 20, None),
    "windmill0": (B, [150, 278, 310, 482], 3.6, 20, None),
    "lamp0": (None, [357, 904, 381, 987], 4.2, 7, None),
    "well0": (None, [1397, 636, 1446, 700], 3, 10, None),
    "log0": (None, [1191, 431, 1254, 477], 3, 7, None),
}

def reroof(im, hue):
    """Turns the red roof tiles another colour (hue in degrees), keeping their light and shade."""
    import colorsys
    a = np.asarray(im).copy()
    for y in range(a.shape[0]):
        for x in range(a.shape[1]):
            r, g, b, al = a[y, x]
            if not al: continue
            hh, ss, vv = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
            if (hh < 0.03 or hh > 0.93) and ss > 0.4 and vv > 0.35:
                if 90 < hue < 150: ss, vv = ss * 0.7, vv * 0.85  # a softer, mossier green
                rr, gg, bb = colorsys.hsv_to_rgb(hue / 360, ss, vv)
                a[y, x, :3] = (int(rr * 255), int(gg * 255), int(bb * 255))
    return Image.fromarray(a, "RGBA")

chars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
lines = ["// Generated by client/scripts/mkprops.py from the user's tileset sheet (2026-10-11). Do not edit by hand.",
         "/** A prop picture: palette, then one character per pixel (\".\" = clear), `scale` screen pixels per pixel. */",
         "export interface PropSprite { w: number; h: number; scale: number; pal: string[]; px: string }",
         "export const PROP_SPRITES: Record<string, PropSprite> = {"]
prev = []
for name, (sheet, box, cell, colors, hue) in SPRITES.items():
    scale = 3
    raw = cut(sheet or src, box, cell, colors=32, outline=False, bg=Image.open(sheet).convert("RGB").getpixel((3, 3)) if sheet else OLD)
    # big pictures keep their detail (no speck clean-up); small ones are simplified hard
    im = clean(raw, colors=colors, passes=0 if colors >= 20 else 1)
    if hue is not None: im = reroof(im, hue)
    im = outline(im)
    prev.append(im)
    w, h = im.size
    pal, px = [], []
    for y in range(h):
        for x in range(w):
            r, g, b, a = im.getpixel((x, y))
            if a < 128: px.append("."); continue
            hx = "%02x%02x%02x" % (r, g, b)
            if hx not in pal: pal.append(hx)
            px.append(chars[pal.index(hx)])
    assert len(pal) <= len(chars), name
    lines.append(f'  {name}: {{ w: {w}, h: {h}, scale: {scale}, pal: {json.dumps(pal)}, px: "{"".join(px)}" }},')
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
W = sum(i.width for i in prev) + 4 * len(prev); H = max(i.height for i in prev)
s = Image.new("RGBA", (W, H), (120, 190, 70, 255)); x = 0
for i in prev: s.alpha_composite(i, (x, H - i.height)); x += i.width + 4
s.resize((W * 4, H * 4), Image.NEAREST).save(sys.argv[4])
