"""Builds client/src/worldProps.data.ts: the Open World props cut from the user's tileset sheet and
redrawn as crisp pixel art (see pixelize.py). Each sprite: palette + one character per pixel."""
import sys, json
sys.path.insert(0, sys.argv[3])
from pixelize import cut
from PIL import Image
src, out = sys.argv[1], sys.argv[2]
SPRITES = {
    # name: (box on the sheet, cell size, screen pixels per sprite pixel)
    "tree0": ([27, 431, 82, 504], 3, 3), "tree1": ([86, 432, 136, 502], 3, 3), "tree2": ([196, 433, 249, 502], 3, 3),
    "blossom0": ([258, 428, 312, 503], 3, 3),
    "pine0": ([318, 432, 360, 502], 3, 3), "pine1": ([367, 425, 417, 500], 3, 3),
    "bush0": ([32, 509, 75, 548], 3, 3), "bush1": ([86, 508, 128, 548], 3, 3), "bush2": ([268, 509, 312, 550], 3, 3), "bush3": ([319, 506, 362, 550], 3, 3),
    "rock0": ([34, 606, 74, 643], 3, 3), "rock1": ([91, 609, 130, 644], 3, 3),
    "house0": ([32, 752, 109, 850], 3, 5), "house1": ([124, 752, 197, 850], 3, 5), "house2": ([203, 756, 274, 850], 3, 5), "house3": ([280, 756, 351, 850], 3, 5),
    "stall0": ([31, 905, 93, 992], 3, 3),
    "lamp0": ([357, 904, 381, 987], 3, 2),
    "well0": ([1397, 636, 1446, 700], 3, 2),
    "log0": ([1191, 431, 1254, 477], 3, 3),
}
chars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
lines = ["// Generated by client/scripts/worldprops/mkprops.py from the user's tileset sheet (2026-10-11). Do not edit by hand.",
         "/** A prop picture: palette, then one character per pixel (\".\" = clear), `scale` screen pixels per pixel. */",
         "export interface PropSprite { w: number; h: number; scale: number; pal: string[]; px: string }",
         "export const PROP_SPRITES: Record<string, PropSprite> = {"]
prev = []
for name, (box, cell, scale) in SPRITES.items():
    im = cut(src, box, cell)
    prev.append(im)
    w, h = im.size
    pal, px = [], []
    for y in range(h):
        for x in range(w):
            r, g, b, a = im.getpixel((x, y))
            if a < 128: px.append("."); continue
            hx = "%02x%02x%02x" % (r, g, b)
            if hx not in pal: pal.append(hx)
            px.append(chars[pal.index(hx)])
    assert len(pal) <= len(chars), name
    lines.append(f'  {name}: {{ w: {w}, h: {h}, scale: {scale}, pal: {json.dumps(pal)}, px: "{"".join(px)}" }},')
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
W = sum(i.width for i in prev) + 4 * len(prev); H = max(i.height for i in prev)
s = Image.new("RGBA", (W, H), (120, 190, 70, 255)); x = 0
for i in prev: s.alpha_composite(i, (x, H - i.height)); x += i.width + 4
s.resize((W * 4, H * 4), Image.NEAREST).save(sys.argv[4])
