"""Draws the Open World stone lamp as crisp pixel art after the user's 16-frame lamp sheet
(art/props/src/lamp-sheet.png): a stone post on a mossy plinth, a glowing lantern that flickers and a few
sparks round it. Writes art/props/lamp_0..7.png. Run in client/: python3 scripts/worldprops/lamp.py"""
import os, sys, random
import numpy as np
from PIL import Image
sys.path.insert(0, os.path.dirname(__file__))
from pixelize import outline

# 13 wide. Letters: stone L(lit) S M(mid) D(dark) K(deep); G glass glow levels 1 (edge) 2 3 (core); m moss.
ART = """
......L......
.....LSM.....
....LSSMD....
...LSSSSMD...
..LSSSSSMMD..
..KKKKKKKKK..
...S12321D...
...S23332D...
...S23332D...
...S23332D...
...S12321D...
..LSSSSSMMD..
...KKKKKKK...
....LSSMD....
.....3S2.....
.....SMD.....
.....SMD.....
.....SMD.....
....LSSMD....
....KKKKK....
.....SMD.....
.....SMD.....
.....SMD.....
....LSMMD....
...LSSSMMD...
..LSSmSMMDD..
..SSmmSMMmD..
..LSSSMMmDD..
..KKKKKKKKK..
"""
H = lambda s: tuple(int(s[i:i + 2], 16) for i in (0, 2, 4))
STONE = {"L": "d6d0e0", "S": "b4accb", "M": "958ca8", "D": "746c88", "K": "4e485e", "m": "6aa044"}
GLOW = [  # edge, mid, core per flicker level
    ("e08a36", "f8c060", "fff0c0"),
    ("e89640", "fcca6c", "fff6d4"),
    ("d47c2e", "f0b04e", "ffe6a8"),
]
rows = [r for r in ART.strip("\n").split("\n")]
h, w = len(rows), len(rows[0])
random.seed(7)
SPARK = [(1, 7), (11, 7), (0, 9), (12, 9), (1, 11), (11, 11), (2, 5), (10, 5)]
for f in range(8):
    lv = [0, 1, 1, 0, 2, 0, 1, 2][f]
    a = np.zeros((h, w, 4), np.uint8)
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch == ".": continue
            c = GLOW[lv][int(ch) - 1] if ch.isdigit() else STONE[ch]
            a[y, x, :3] = H(c); a[y, x, 3] = 255
    im = outline(Image.fromarray(a, "RGBA"))  # 1px border all round: sparks go in it, unoutlined
    p = np.asarray(im).copy()
    for i, (sx, sy) in enumerate(SPARK):
        if (i + f) % 4 == 0:
            p[sy + 1, sx + 1] = (*H("ffd27a"), 255)
    Image.fromarray(p, "RGBA").save(f"art/props/lamp_{f}.png")
print(w + 2, h + 2)
